uint32_t baseChar(uint8_t b) {
    if (b < 0x80) return kAscii[b];
    for (std::size_t i = 0; i < sizeof(kUpper) / sizeof(kUpper[0]); ++i) {
        if (kUpper[i].byte == b) return kUpper[i].cp;
    }
    return 0xFFFD;
}

