bool isControlCode(uint8_t value) { return value < 0x20 || value == 0x7F; }

std::string byteToUtf8(uint8_t value) {
    std::string out;
    if (value == 0xFE || value == 0xFF) {
        utf8::append(out, 0xF000u + value);
        return out;
    }
    const uint32_t cp = baseChar(value);
    utf8::append(out, cp);
    return out;
}

std::string decode(const uint8_t* data, std::size_t size) {
    std::string out;
    for (std::size_t i = 0; i < size; ++i) {
        const uint8_t b = data[i];
        if (b == 0x01 && i + 1 < size && data[i + 1] >= 0x41 && data[i + 1] <= 0x5F) {
            utf8::append(out, kGraphic[data[i + 1] - 0x41]);
            ++i;
            continue;
        }
        if (i + 1 < size && (data[i + 1] == 0xDE || data[i + 1] == 0xDF)) {
            bool found = false;
            for (std::size_t k = 0; k < sizeof(kComposed) / sizeof(kComposed[0]); ++k) {
                if (kComposed[k].base == b && kComposed[k].mark == data[i + 1]) {
                    utf8::append(out, kComposed[k].cp);
                    ++i;
                    found = true;
                    break;
                }
            }
            if (found) continue;
        }
        out += byteToUtf8(b);
    }
    return out;
}

std::string decode(const Bytes& data) { return decode(data.empty() ? nullptr : &data[0], data.size()); }

EncodeStatus encode(const std::string& text, Bytes& out, EncodeError* error) {
    std::size_t i = 0;
    while (i < text.size()) {
        const std::size_t start = i;
        uint32_t cp = 0;
        if (!utf8::decode(text, i, cp)) {
            if (error) {
                error->status = EncodeStatus::MalformedUtf8;
                error->byteOffset = start;
                error->codePoint = 0;
            }
            return EncodeStatus::MalformedUtf8;
        }
        // Lossless private-use round trip for bytes with no Unicode mapping.
        if (cp >= 0xF000 && cp <= 0xF0FF) {
            out.push_back(static_cast<uint8_t>(cp - 0xF000));
            continue;
        }
        // ASCII.  U+005C is not representable: MSX 0x5C is the yen sign.
        if (cp < 0x80) {
            if (cp == 0x0000) {
                if (error) {
                    error->status = EncodeStatus::UnknownCharacter;
                    error->byteOffset = start;
                    error->codePoint = cp;
                }
                return EncodeStatus::UnknownCharacter;
            }
            if (cp == 0x005C) {
                if (error) {
                    error->status = EncodeStatus::UnknownCharacter;
                    error->byteOffset = start;
                    error->codePoint = cp;
                }
                return EncodeStatus::UnknownCharacter;
            }
            out.push_back(static_cast<uint8_t>(cp));
            continue;
        }
        if (cp == 0x00A5) {
            out.push_back(0x5C);
            continue;
        }
        // Full-width ASCII forms (U+FF01..U+FF5E) are normalized to the MSX
        // single-byte ASCII set; the Japanese MSX font has no full-width Latin.
        if (cp >= 0xFF01 && cp <= 0xFF5E) {
            const uint8_t ascii = static_cast<uint8_t>(cp - 0xFEE0);
            if (ascii == 0x5C) {
                if (error) {
                    error->status = EncodeStatus::UnknownCharacter;
                    error->byteOffset = start;
                    error->codePoint = cp;
                }
                return EncodeStatus::UnknownCharacter;
            }
            out.push_back(ascii);
            continue;
        }
        // Extended graphic characters (0x01 + 0x41..0x5F).
        bool handled = false;
        for (std::size_t g = 0; g < sizeof(kGraphic) / sizeof(kGraphic[0]); ++g) {
            if (kGraphic[g] == cp) {
                out.push_back(0x01);
                out.push_back(static_cast<uint8_t>(0x41 + g));
                handled = true;
                break;
            }
        }
        if (handled) continue;
        // Dakuten composition.
        for (std::size_t k = 0; k < sizeof(kComposed) / sizeof(kComposed[0]); ++k) {
            if (kComposed[k].cp == cp) {
                out.push_back(kComposed[k].base);
                out.push_back(kComposed[k].mark);
                handled = true;
                break;
            }
        }
        if (handled) continue;
        // Half-width katakana compatibility.
        for (std::size_t k = 0; k < sizeof(kHalfWidth) / sizeof(kHalfWidth[0]); ++k) {
            if (kHalfWidth[k].cp == cp) {
                cp = kHalfWidth[k].fullWidth;
                break;
            }
        }
        // Canonical direct mapping (U+3000 -> 0xA0, else first non-0x90 byte).
        if (cp == 0x3000) {
            out.push_back(0xA0);
            continue;
        }
        for (std::size_t k = 0; k < sizeof(kUpper) / sizeof(kUpper[0]); ++k) {
            if (kUpper[k].cp == cp && kUpper[k].byte != 0x90) {
                out.push_back(kUpper[k].byte);
                handled = true;
                break;
            }
        }
        if (handled) continue;
        if (error) {
            error->status = EncodeStatus::UnknownCharacter;
            error->byteOffset = start;
            error->codePoint = cp;
        }
        return EncodeStatus::UnknownCharacter;
    }
    return EncodeStatus::Ok;
}

